// Возвращает промис, чтобы страница уже работала с загрузкой и ошибкой,
// как будет с настоящим запросом.
export function getCards(schoolId) {
  return new Promise((resolve, reject) => {
    setTimeout(() => {
      if (!schoolId) return resolve(tpuCards)
      const school = getSchool(schoolId)
      if (!school) return reject(new Error('school not found'))
      resolve(schoolCards(school))
    }, 300)
  })
}
